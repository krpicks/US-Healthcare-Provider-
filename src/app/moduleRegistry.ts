export function getModuleByRoute(pathname: string): ModuleDefinition | undefined {
  return getAllRegistryEntries().find(
    (entry) => pathname === entry.route || pathname.startsWith(`${entry.route}/`),
  );
}

export function getModulesByGroup(group: ModuleGroup): ModuleDefinition[] {
  return MODULE_REGISTRY.filter((entry) => entry.group === group);
}
